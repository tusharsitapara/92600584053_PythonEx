print(type(name))

num = 120
print(type(num))

n = 1.20
print(type(n))

x = 2 + 2j
print(type(x))

i = True
print(type(i))

j = [1,2,3,4]
print(type(j))

h = (1,2,3,4,5)
print(type(h))

